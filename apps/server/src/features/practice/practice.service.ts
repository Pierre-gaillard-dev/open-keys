import type {
  Loop,
  PracticeSession,
  PracticeStats,
  PutLoopRequest,
  PutPracticeSessionRequest,
} from "@open-keys/contracts";
import type { Database } from "../../db";
import { AppError } from "../../shared/http";
import type { Clock } from "../../shared/runtime";
import type { SongsService } from "../songs";
import {
  findLoop,
  findPracticeSession,
  type LoopRow,
  listActiveLoops,
  type PracticeSessionRow,
  practiceTotals,
  upsertLoop,
  upsertPracticeSession,
} from "./practice.queries";

export interface PracticeServiceDeps {
  readonly db: Database;
  readonly clock: Clock;
  readonly songs: SongsService;
}

export type PracticeService = ReturnType<typeof createPracticeService>;

function toLoop(row: LoopRow): Loop {
  const { userId: _userId, ...loop } = row;
  return loop;
}

function toPracticeSession(row: PracticeSessionRow): PracticeSession {
  const { userId: _userId, ...session } = row;
  return session;
}

/** Ids are generated by clients: a row of another user is reported as missing, never overwritten. */
function assertOwnedOrNew(row: { userId: string } | undefined, userId: string, what: string): void {
  if (row && row.userId !== userId) {
    throw new AppError("NOT_FOUND", `${what} not found`);
  }
}

export function createPracticeService({ db, clock, songs }: PracticeServiceDeps) {
  const requireOwnedLoop = (userId: string, id: string): LoopRow => {
    const loop = findLoop(db, id);
    if (!loop || loop.userId !== userId) {
      throw new AppError("NOT_FOUND", "Loop not found");
    }
    return loop;
  };

  const ownsActiveLoop = (userId: string, songId: string, loopId: string): boolean => {
    const loop = findLoop(db, loopId);
    return loop?.userId === userId && loop.songId === songId && loop.deletedAt === null;
  };

  return {
    listLoops(userId: string, songId: string): Loop[] {
      songs.requireSong(songId);
      return listActiveLoops(db, userId, songId).map(toLoop);
    },

    putLoop(userId: string, id: string, request: PutLoopRequest): Loop {
      const existing = findLoop(db, id);
      assertOwnedOrNew(existing, userId, "Loop");
      if (existing && existing.songId !== request.songId) {
        throw new AppError("CONFLICT", "A loop cannot move to another song");
      }
      songs.requireSong(request.songId);
      upsertLoop(db, { ...request, id, userId });
      return toLoop(requireOwnedLoop(userId, id));
    },

    deleteLoop(userId: string, id: string): void {
      const loop = requireOwnedLoop(userId, id);
      const now = clock();
      upsertLoop(db, { ...loop, deletedAt: now, updatedAt: Math.max(now, loop.updatedAt) });
    },

    /** Used by the library: the last active loop must be one of the user's loops. */
    ownsActiveLoop,

    putSession(userId: string, id: string, request: PutPracticeSessionRequest): PracticeSession {
      const existing = findPracticeSession(db, id);
      assertOwnedOrNew(existing, userId, "Practice session");
      songs.requireSong(request.songId);
      const loopId =
        request.loopId && ownsActiveLoop(userId, request.songId, request.loopId) ? request.loopId : null;
      upsertPracticeSession(db, { ...request, loopId, id, userId });
      const stored = findPracticeSession(db, id);
      if (!stored) {
        throw new AppError("INTERNAL_ERROR", "Practice session was not stored");
      }
      return toPracticeSession(stored);
    },

    stats(userId: string, songId: string): PracticeStats {
      songs.requireSong(songId);
      const totals = practiceTotals(db, userId, songId);
      return {
        songId,
        totalActiveMs: totals?.totalActiveMs ?? 0,
        sessionCount: totals?.sessionCount ?? 0,
        lastPracticedAt: totals?.lastPracticedAt ?? null,
      };
    },
  };
}
