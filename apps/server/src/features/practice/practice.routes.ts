import {
  idParamSchema,
  type Loop,
  type PracticeSession,
  type PracticeStats,
  putLoopRequestSchema,
  putPracticeSessionRequestSchema,
  songIdParamSchema,
} from "@open-keys/contracts";
import { Hono } from "hono";
import { type AuthedEnv, validate } from "../../shared/http";
import type { PracticeService } from "./practice.service";

/** /songs/:id/loops and /songs/:id/practice-stats */
export function createSongPracticeRoutes(service: PracticeService) {
  return new Hono<AuthedEnv>()
    .get("/:id/loops", validate("param", songIdParamSchema), (c) =>
      c.json<Loop[]>(service.listLoops(c.var.user.id, c.req.valid("param").id)),
    )
    .get("/:id/practice-stats", validate("param", songIdParamSchema), (c) =>
      c.json<PracticeStats>(service.stats(c.var.user.id, c.req.valid("param").id)),
    );
}

/** /loops/:id — ids are ULIDs generated by the client (offline creation, idempotent PUT). */
export function createLoopsRoutes(service: PracticeService) {
  return new Hono<AuthedEnv>()
    .put("/:id", validate("param", idParamSchema), validate("json", putLoopRequestSchema), (c) =>
      c.json<Loop>(service.putLoop(c.var.user.id, c.req.valid("param").id, c.req.valid("json"))),
    )
    .delete("/:id", validate("param", idParamSchema), (c) => {
      service.deleteLoop(c.var.user.id, c.req.valid("param").id);
      return c.body(null, 204);
    });
}

/** /practice-sessions/:id */
export function createPracticeSessionsRoutes(service: PracticeService) {
  return new Hono<AuthedEnv>().put(
    "/:id",
    validate("param", idParamSchema),
    validate("json", putPracticeSessionRequestSchema),
    (c) =>
      c.json<PracticeSession>(
        service.putSession(c.var.user.id, c.req.valid("param").id, c.req.valid("json")),
      ),
  );
}
